// 1. Sıcaklık Okuma Fonksiyonu (ADC)
void Read_Temperature(void) {
    HAL_ADC_Start(&hadc1);
    // ADC dönüşümünün bitmesini bekle
    if(HAL_ADC_PollForConversion(&hadc1, 100) == HAL_OK) {
        uint32_t adc_val = HAL_ADC_GetValue(&hadc1);
        // Örnek analog sıcaklık sensörü (örn. LM35) hesaplaması (3.3V referans, 12-bit)
        temperature = (adc_val * 3.3 / 4095.0) * 100.0;
    }
    HAL_ADC_Stop(&hadc1);
}

// 2. PC'ye Veri Gönderme Fonksiyonu (UART)
void Send_UART_Data(void) {
    // Verileri formatlayarak uart_buf dizisine yaz
    sprintf(uart_buf, "Mod: %d | Sicaklik: %.1f C | Hareket: %d\r\n", system_mode, temperature, motion_detected);
    // UART üzerinden gönder
    HAL_UART_Transmit(&huart2, (uint8_t*)uart_buf, strlen(uart_buf), 100);
}

// 3. Buton Kesmesi (EXTI Callback) - Mod Değiştirme
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
    // Eğer kesmeyi üreten pin bizim PA0 (WKUP) pini ise
    if(GPIO_Pin == GPIO_PIN_0) {
        system_mode = !system_mode; // Modu 0'sa 1, 1'se 0 yap
    }
}

